SYSTEM_PROMPTS: dict[str, str] = {
    "analyst": ANALYST_PROMPT,
    "dormitory": DORMITORY_PROMPT,
    "cost": COST_PROMPT,
    "exams": EXAMS_PROMPT,
}


def format_chunks(chunks: list[Chunk]) -> str:
    """Развернуть найденные фрагменты в текстовый блок с метаданными."""
    if not chunks:
        return "(база знаний ничего не вернула)"
    return "\n\n".join(
        f"[{c.source}, стр. {c.page}] (близость {c.score})\n{c.text}" if c.page
        else f"[{c.source}] (близость {c.score})\n{c.text}"
        for c in chunks
    )


def build_messages(role: str, question: str, chunks: list[Chunk],
                   history: list[Message]) -> list[dict]:
    """Собрать сообщения в порядке system, история, фрагменты и вопрос."""
    system_prompt = SYSTEM_PROMPTS.get(role, ANALYST_PROMPT)
    messages = [{"role": "system", "content": system_prompt}]
    messages.extend(
        {"role": message.role, "content": message.content}
        for message in history
    )
    messages.append({
        "role": "user",
        "content": (
            f"Найденные фрагменты:\n{format_chunks(chunks)}"
            f"\n\nВопрос: {question}"
        ),
    })
    return messages
